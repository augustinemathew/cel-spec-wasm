absl::StatusOr<std::string> EmitUserFnsH(
    const FunctionLibrary& lib, absl::string_view cpp_namespace,
    const std::vector<std::string>& extra_includes) {
  IncludeProbe probe;
  for (const auto& d : lib.decls()) {
    if (d.backend != CelfnDecl::Backend::kForeignComponent) continue;
    ProbeType(d.return_type, &probe);
    for (const auto& p : d.params) ProbeType(p.type, &probe);
  }

  std::string out;
  absl::StrAppend(
      &out,
      "// Generated by `cel generate` — author-facing declarations.\n"
      "// Implement the bodies in user_fns.cc; everything else is\n"
      "// generated.  Re-running `cel generate` REGENERATES this file\n"
      "// and does NOT overwrite user_fns.cc.\n\n");
  absl::StrAppend(&out, "#pragma once\n\n");
  // Standard set: emitted unconditionally to match the codec.h /
  // generated_stub.cc convention.  Cheap, and avoids fragile
  // include-resolution churn when an author adds a new decl.
  absl::StrAppend(&out, "#include <cstdint>\n");
  absl::StrAppend(&out, "#include <map>\n");
  absl::StrAppend(&out, "#include <string>\n");
  absl::StrAppend(&out, "#include <string_view>\n");
  if (probe.needs_variant) absl::StrAppend(&out, "#include <variant>\n");
  absl::StrAppend(&out, "#include <vector>\n");
  absl::StrAppend(&out, "\n");
  if (probe.needs_absl_time) {
    absl::StrAppend(&out, "#include \"absl/time/time.h\"\n");
  }
  for (const auto& inc : extra_includes) {
    absl::StrAppend(&out, "#include \"", inc, "\"\n");
  }
  if (probe.needs_absl_time || !extra_includes.empty()) {
    absl::StrAppend(&out, "\n");
  }

  const bool has_ns = !cpp_namespace.empty();
  if (has_ns) {
    absl::StrAppend(&out, "namespace ", cpp_namespace, " {\n\n");
  }

  for (const auto& d : lib.decls()) {
    if (d.backend != CelfnDecl::Backend::kForeignComponent) continue;
    auto ret = CppType(d.return_type, /*as_param=*/false);
    if (!ret.ok()) return ret.status();
    std::vector<std::string> params;
    params.reserve(d.params.size());
    for (const auto& p : d.params) {
      auto pty = CppType(p.type, /*as_param=*/true);
      if (!pty.ok()) return pty.status();
      params.push_back(absl::StrCat(*pty, " ", p.name));
    }
    absl::StrAppend(&out, *ret, " ", SnakeToCamel(d.fn_name), "(",
                    absl::StrJoin(params, ", "), ");\n");
  }

  if (has_ns) {
    absl::StrAppend(&out, "\n}  // namespace ", cpp_namespace, "\n");
  }
  return out;
}

