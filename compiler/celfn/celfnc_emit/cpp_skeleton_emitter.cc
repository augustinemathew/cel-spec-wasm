// CelfnType → idiomatic C++ author-facing type.  Used for params
// AND returns; param/return shape differs slightly:
//   - strings: param `std::string_view`, return `std::string`.
//   - aggregates: param `const std::vector<...>&` etc., return by
//     value.
//   - protos: param `const acme::User&`, return `acme::User`.
//   - scalars: always pass-by-value.
//
// `as_param` controls which shape we emit.
absl::StatusOr<std::string> CppType(const CelfnType& t, bool as_param) {
  using K = CelfnType::Kind;
  switch (t.kind) {
    case K::kBool:
      return std::string("bool");
    case K::kInt:
      return std::string("int64_t");
    case K::kUint:
      return std::string("uint64_t");
    case K::kDouble:
      return std::string("double");
    case K::kString:
      return std::string(as_param ? "std::string_view" : "std::string");
    case K::kBytes:
      return std::string(as_param ? "const std::vector<uint8_t>&"
                                  : "std::vector<uint8_t>");
    case K::kNull:
      return std::string("std::monostate");
    case K::kDuration:
      return std::string("absl::Duration");
    case K::kTimestamp:
      return std::string("absl::Time");
    case K::kList: {
      auto inner = CppType(t.list_element[0], /*as_param=*/false);
      if (!inner.ok()) return inner.status();
      const std::string body = absl::StrCat("std::vector<", *inner, ">");
      return std::string(as_param ? absl::StrCat("const ", body, "&") : body);
    }
    case K::kMap: {
      auto k = CppType(t.map_kv[0], /*as_param=*/false);
      auto v = CppType(t.map_kv[1], /*as_param=*/false);
      if (!k.ok()) return k.status();
      if (!v.ok()) return v.status();
      const std::string body = absl::StrCat("std::map<", *k, ", ", *v, ">");
      return std::string(as_param ? absl::StrCat("const ", body, "&") : body);
    }
    case K::kProto: {
      const std::string ns = absl::StrReplaceAll(t.proto_fqn, {{".", "::"}});
      return std::string(as_param ? absl::StrCat("const ", ns, "&") : ns);
    }
    case K::kOptional:
    case K::kType:
      return absl::FailedPreconditionError(
          "skeleton emitter saw a permanently-rejected CelfnType::Kind");
  }
  return absl::InternalError("CppType: unknown kind");
}

// Walk every type in lib; return true if any uses `Duration` /
// `Timestamp` (so we know whether to emit `absl/time/time.h`).
// Same idea for proto headers — but those are explicit
// `extra_includes` from the macro caller.
struct IncludeProbe {
  bool needs_absl_time = false;
  bool needs_variant = false;
  bool needs_map = false;
  bool needs_vector = false;
  bool needs_cstdint = false;
};

void ProbeType(const CelfnType& t, IncludeProbe* p) {
  using K = CelfnType::Kind;
  switch (t.kind) {
    case K::kBool:
      break;
    case K::kInt:
    case K::kUint:
      p->needs_cstdint = true;
      break;
    case K::kDouble:
      break;
    case K::kNull:
      p->needs_variant = true;
      break;
    case K::kDuration:
    case K::kTimestamp:
      p->needs_absl_time = true;
      break;
    case K::kBytes:
      p->needs_vector = true;
      p->needs_cstdint = true;
      break;
    case K::kList:
      p->needs_vector = true;
      if (!t.list_element.empty()) ProbeType(t.list_element[0], p);
      break;
    case K::kMap:
      p->needs_map = true;
      if (t.map_kv.size() == 2) {
        ProbeType(t.map_kv[0], p);
        ProbeType(t.map_kv[1], p);
      }
      break;
    case K::kString:
    case K::kProto:
    case K::kOptional:
    case K::kType:
      break;
  }
}

